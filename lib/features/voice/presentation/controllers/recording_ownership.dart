/// Чья серверная запись и когда уход из звонка вправе её остановить.
///
/// Запись принадлежит тому, кто её начал. Раньше её «присваивал» любой
/// участник из приложения, заставший рекордер в комнате при входе, а уход из
/// звонка у владельца останавливает запись — и 17.11.2026 владелец комнаты,
/// перейдя с телефона обратно в веб, оборвал запись всем на середине часовой
/// встречи. Веб чужую запись своей не считает и при уходе её не трогает.
///
/// Остановить запись при уходе можно только последним: пока в комнате кто-то
/// есть, встреча продолжается и запись нужна. Когда выходят все, рекордер
/// останавливается сам (`livekit-agent/recorder.js`, «All humans left»), так
/// что за пределами этого правила останавливать её некому и незачем.
///
/// Вынесено из экрана звонка по той же причине, что и [RecordingDialect]:
/// экран в тесте не поднять, а ошибка здесь стоит целой встречи.
class RecordingOwnership {
  /// Участник, которым рекордер входит в комнату.
  static const String recorderIdentity = 'meeting-recorder';

  static const Set<String> _serviceIdentities = {
    recorderIdentity,
    'ai-assistant',
    'voice-translator',
  };

  /// Человек ли участник, а не служебный бот комнаты.
  static bool isPerson(String identity) =>
      !_serviceIdentities.contains(identity);

  /// Останавливать ли серверную запись, уходя из звонка.
  ///
  /// Только свою, только идущую и только последним из людей. Если комната
  /// уже не на связи (уход по обрыву), список участников пуст или устарел, и
  /// «никого не осталось» значило бы лишь «мы больше не видим комнату» —
  /// тогда решать оставляем рекордеру.
  static bool stopOnLeave({
    required String? localId,
    required String? initiatorId,
    required bool active,
    required bool roomConnected,
    required Iterable<String> remoteIdentities,
  }) {
    if (localId == null || initiatorId != localId) return false;
    if (!active || !roomConnected) return false;
    return !remoteIdentities.any(isPerson);
  }

  /// Сбрасывать ли своё представление о записи, когда рекордер ушёл из
  /// комнаты.
  ///
  /// Зритель чужой записи держит кнопку записи выключенной, пока запись идёт.
  /// Обычно об окончании сообщает инициатор, но вошедший посреди записи его
  /// не знает, а рекордер может уйти и без сообщения — упасть, перезапуститься
  /// с деплоем. Без сброса кнопка осталась бы мёртвой до конца звонка.
  /// Инициатор своё состояние не трогает: кнопка «Стоп» у него остаётся.
  static bool resetWhenRecorderLeft({
    required String? localId,
    required String? initiatorId,
  }) =>
      localId == null || initiatorId != localId;
}
