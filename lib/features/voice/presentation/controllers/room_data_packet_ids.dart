import 'package:uuid/uuid.dart';

/// Идентификаторы пакетов data-канала звонка: выдача своих и отсев чужих
/// дублей. Вынесено из экрана звонка отдельным классом, потому что связка
/// «выдал id — сосед его запомнил» проверяема только целиком, а экран
/// поднять в тесте нельзя (LiveKit, DI, разрешения).
///
/// Ключевое свойство — **префикс уникален на экземпляр**, а не на участника.
/// Экземпляр живёт ровно столько же, сколько состояние экрана звонка, тогда
/// как identity участника переживает сворачивание звонка: `_minimizeCall()`
/// делает `context.pop()`, экран уничтожается, а комната продолжает работать
/// в `CallStateService`. Если бы префиксом была identity, то после возврата
/// счётчик пошёл бы с нуля, выдал бы уже использованные id — и собеседник
/// молча отбросил бы первые сообщения как дубли. Отправитель при этом видел
/// бы свой пузырь: потеря была бы совершенно незаметной.
///
/// Отправителя в id класть не нужно: id служит только дедупликации, а автор
/// пакета приходит отдельным полем/участником события.
class RoomDataPacketIds {
  /// Сколько чужих id помним. При переполнении набор очищается целиком —
  /// поведение унаследовано от экрана: за время звонка до потолка доходят
  /// разве что очень болтливые комнаты, а точность LRU тут не нужна.
  static const int maxRemembered = 200;

  final String _prefix;
  int _seq = 0;
  final Set<String> _seen = {};

  /// [prefix] задаётся только в тестах; в бою всегда свежий uuid.
  RoomDataPacketIds({String? prefix}) : _prefix = prefix ?? const Uuid().v4();

  /// Следующий идентификатор исходящего пакета.
  String next() => '${_prefix}_${_seq++}';

  /// true — пакет с таким id уже видели, обрабатывать его не нужно.
  /// Незнакомый id запоминается тут же, поэтому вызывать ровно один раз
  /// на входящий пакет.
  bool isDuplicate(String msgId) {
    if (!_seen.add(msgId)) return true;
    if (_seen.length > maxRemembered) _seen.clear();
    return false;
  }
}
