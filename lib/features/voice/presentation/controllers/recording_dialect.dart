/// Два диалекта одного протокола согласия на запись.
///
/// Веб-комната и приложение пишут в один data-канал LiveKit, но исторически
/// разными семействами пакетов. Веб различает запись локально в браузер
/// (`recording_*`) и запись на сервер (`srv_rec_*`). У приложения запись
/// всегда серверная — тот же `recorder/start`, — но названа семейством
/// `recording_*`, и разбор входящих был switch'ем без ветки по умолчанию:
/// незнакомый тип выбрасывался молча. Поэтому запись на сервер, начатая из
/// веба, до участника в приложении не доходила вовсе — диалог согласия не
/// появлялся, а инициатор ждал ответа вечно.
///
/// Пока в ходу сборки, знающие только `recording_*`, каждый пакет серверной
/// записи уходит в двух диалектах: родной `srv_rec_*` и дублёр `recording_*`
/// с пометкой [twinFlag]. Обе стороны узнают свои дублёры по пометке и
/// пропускают их — иначе участник получил бы два диалога на одно согласие.
/// Встречная половина живёт в `public/room.html` бэкенда.
///
/// Вынесено из экрана звонка отдельным классом по той же причине, что и
/// [RoomDataPacketIds]: экран в тесте не поднять (LiveKit, DI, разрешения), а
/// ошибиться тут легко и незаметно — см. проверку про `msgId` ниже.
///
/// Когда `srv_rec_*` появится во всех живых сборках, дублёры и пометку можно
/// снять, и протокол вернётся к одному диалекту.
class RecordingDialect {
  /// Поле, которым помечен дублёр для сборок без `srv_rec_*`.
  static const String twinFlag = 'srvRec';

  /// Какому обработчику отдать пакет серверной записи. Значение — тип из
  /// семейства, которое экран разбирал и раньше, так что новых обработчиков
  /// заводить не нужно: у приложения это одна и та же запись.
  static const Map<String, String> _serverToLegacy = {
    'srv_rec_consent_request': 'recording_consent_request',
    'srv_rec_consent_response': 'recording_consent_response',
    'srv_rec_approved': 'recording_approved',
    'srv_rec_denied': 'recording_denied',
    'srv_rec_ended': 'recording_ended',
  };

  /// true — пакет прислан как дублёр для старых сборок. Свой диалект мы
  /// разбираем сами, поэтому дублёр надо пропустить, иначе одно согласие
  /// обработается дважды.
  ///
  /// Пометка засчитывается только настоящим `true`: поле приходит из JSON от
  /// другого клиента и может оказаться чем угодно, а ошибиться безопаснее в
  /// сторону лишней обработки, чем молчания.
  static bool isTwin(Map<String, dynamic> msg) => msg[twinFlag] == true;

  static final Map<String, String> _legacyToServer = {
    for (final e in _serverToLegacy.entries) e.value: e.key,
  };

  /// Тип, к обработчику которого свести пакет серверной записи, или null,
  /// если пакет не про неё.
  static String? legacyTypeFor(String type) => _serverToLegacy[type];

  /// Родной тип серверной записи для прежнего [legacyType], или null, если
  /// пары нет. Нужен на отправке: приложение исторически звало серверную
  /// запись прежним семейством, из-за чего веб на её запрос рисовал диалог
  /// про запись в браузер. Типы без пары (`recording_denied_late`) остаются
  /// как есть — в веб-диалекте их просто нет.
  static String? serverTypeFor(String legacyType) => _legacyToServer[legacyType];

  /// Дублёр пакета серверной записи для сборок без `srv_rec_*`, или null,
  /// если дублировать нечего.
  ///
  /// Собирать его нужно **до** отправки оригинала: отправка проставляет
  /// `msgId` прямо в переданную карту, и копия, снятая после, унесла бы тот
  /// же идентификатор — приёмная сторона отбросила бы дублёр как повтор.
  /// Идентификатора здесь нет намеренно, его выдаст отправка.
  static Map<String, dynamic>? twinFor(Map<String, dynamic> msg) {
    if (isTwin(msg)) return null; // дублёр дублёра — петля
    final type = msg['type'];
    if (type is! String) return null;
    final legacy = _serverToLegacy[type];
    if (legacy == null) return null;

    final twin = Map<String, dynamic>.from(msg);
    twin.remove('msgId');
    twin['type'] = legacy;
    twin[twinFlag] = true;
    return twin;
  }
}
